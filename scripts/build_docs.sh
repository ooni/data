#!/bin/bash
set -euo pipefail

DOCS_ROOT=dist/docs/
ASSETS_ROOT=dist/public/
REPO_NAME="ooni/data"
MAIN_BRANCH="main"
COMMIT_HASH=$(git rev-parse --short HEAD)
BLOB="https://github.com/$REPO_NAME/blob/$MAIN_BRANCH"
TREE="https://github.com/$REPO_NAME/tree/$MAIN_BRANCH"

rm -rf $DOCS_ROOT $ASSETS_ROOT
mkdir -p $DOCS_ROOT/img
mkdir -p $DOCS_ROOT/pipeline
mkdir -p $ASSETS_ROOT

strip_title() {
    # Since the title is already present in the frontmatter, we need to remove
    # it to avoid duplicate titles
    local infile="$1"
    cat $infile | awk 'BEGIN{p=1} /^#/{if(p){p=0; next}} {print}'
}

generate_doc() {
    local order="$1"
    local slug="$2"
    local input_file="$3"
    local output_file="$4"
    local title="$5"
    local description="$6"

    # title and description are quoted: several contain a colon, which is not
    # valid as an unquoted YAML scalar.
    cat <<EOF>"$DOCS_ROOT/$output_file"
---
# Do not edit! This file is automatically generated
# version: $REPO_NAME/$input_file:$COMMIT_HASH
title: "${title//\"/\\\"}"
description: "${description//\"/\\\"}"
slug: $slug
sidebar:
    order: $order
---
EOF
    echo "[edit file](https://github.com/$REPO_NAME/edit/$MAIN_BRANCH/$input_file)" >> "$DOCS_ROOT/$output_file"
    strip_title "$input_file" >> "$DOCS_ROOT/$output_file"
}

## Accessing OONI data, and the oonidata CLI.
generate_doc 0 "data" "Readme.md" "00-index.md" "Accessing OONI data" "How to access OONI data"
generate_doc 1 "data/oonidata" "oonidata/Readme.md" "01-oonidata.md" "OONI Data CLI" "Using the oonidata command line interface"
cp oonidata/docs/img/* $DOCS_ROOT/img/
generate_doc 2 "data/oonidata-analysis-db" "oonidata/docs/DataAnalysisDB.md" "03-oonidata-analysis-db.md" "OONI Data Analysis DB" "OONI Data Analysis DB"

## The pipeline v5 documentation set, under docs/.
##
## These land in a nested "Pipeline v5" sidebar group, which is autogenerated
## from the directory: adding a document here is enough to make it appear.
##
## Two slugs are inherited from the documents these supersede, so existing
## links keep working: data/pipeline-design (was the Design.md document, now
## Requirements) and data/pipeline (was the oonipipeline Readme, now
## Architecture).
generate_pipeline_doc() {
    local order="$1"
    local slug="$2"
    local name="$3"
    local output_file="$4"
    local title="$5"
    local description="$6"
    generate_doc "$order" "$slug" "docs/$name.md" "pipeline/$output_file" "$title" "$description"
}

generate_pipeline_doc 0 "data/pipeline-design" "requirements" "00-requirements.md" \
    "Requirements" "What the OONI data pipeline must achieve, and how designs are assessed against it"
generate_pipeline_doc 1 "data/pipeline" "architecture" "01-architecture.md" \
    "Architecture" "How the OONI data pipeline is put together: processing tiers, infrastructure and tradeoffs"
generate_pipeline_doc 2 "data/pipeline-ontology" "ontology" "02-ontology.md" \
    "Ontology" "What the pipeline entities mean and what the numbers claim"
generate_pipeline_doc 3 "data/pipeline-implementation-plan" "implementation-plan" "03-implementation-plan.md" \
    "Implementation plan" "Where the pipeline stands today and what the next steps are"
generate_pipeline_doc 4 "data/pipeline-label-corpus" "label-corpus-design" "04-label-corpus.md" \
    "Label corpus" "The ground-truth corpora used to evaluate scoring and detection"
generate_pipeline_doc 5 "data/pipeline-migration-notes" "migration-notes" "05-migration-notes.md" \
    "Migration notes" "Operations to run by hand against a live ClickHouse cluster, in deploy order"
